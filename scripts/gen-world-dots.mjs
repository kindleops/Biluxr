#!/usr/bin/env node
/**
 * Generates the dotted world map used by the site from Natural Earth land
 * polygons (world-atlas, 50m). Output is a compact, committed TS module so the
 * runtime has no geography dependency.   node scripts/gen-world-dots.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

// Projection: equirectangular, cropped to 72°N–56°S, width 1000.
export const BOUNDS = { north: 72, south: -56, west: -170, east: 190 };
const W = 1000;
const H = Math.round((W * (BOUNDS.north - BOUNDS.south)) / (BOUNDS.east - BOUNDS.west));
const STEP = 1.55; // degrees
const dots = [];
let row = 0;
for (let lat = BOUNDS.north; lat >= BOUNDS.south; lat -= STEP, row++) {
  const offset = row % 2 ? STEP / 2 : 0; // hex packing
  for (let lon = BOUNDS.west + offset; lon <= BOUNDS.east; lon += STEP) {
    const l = lon > 180 ? lon - 360 : lon;
    if (geoContains(land, [l, lat])) {
      const x = ((lon - BOUNDS.west) / (BOUNDS.east - BOUNDS.west)) * W;
      const y = ((BOUNDS.north - lat) / (BOUNDS.north - BOUNDS.south)) * H;
      dots.push(`${x.toFixed(1)},${y.toFixed(1)}`);
    }
  }
}
const path = dots
  .map((p) => {
    const [x, y] = p.split(",");
    return `M${x} ${y}h0`;
  })
  .join("");
writeFileSync(
  "public/geo/world-dots.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path d="${path}" fill="none" stroke="#f3efe8" stroke-width="2.1" stroke-linecap="round"/></svg>`,
);
const out = `// Generated by scripts/gen-world-dots.mjs from Natural Earth (public domain). Do not edit.
// The dots themselves live in /public/geo/world-dots.svg (one cacheable asset).
export const WORLD_WIDTH = ${W};
export const WORLD_HEIGHT = ${H};
export const WORLD_BOUNDS = ${JSON.stringify(BOUNDS)};
export const WORLD_DOTS_URL = "/geo/world-dots.svg";
`;
writeFileSync("src/components/geo/world-dots.ts", out);
console.log(`✓ ${dots.length} dots, ${W}x${H}`);
