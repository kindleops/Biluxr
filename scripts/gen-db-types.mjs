#!/usr/bin/env node
/**
 * Generates `src/lib/supabase/database.types.ts` from a migrated database in
 * the shape supabase-js expects. Invoked by `npm run db:types`, which runs it
 * against the disposable Postgres created by scripts/db-test.mjs.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import pg from "pg";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const db = new pg.Client();
await db.connect();

const enums = (
  await db.query(`
    select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder)::text[] as values
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' group by t.typname order by t.typname`)
).rows;
const enumNames = new Set(enums.map((e) => e.name));

const columns = (
  await db.query(`
    select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable, c.column_default is not null as has_default,
           c.is_identity = 'YES' as is_identity, c.data_type, c.udt_name
    from information_schema.columns c
    join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position`)
).rows;

const fks = (
  await db.query(`
    select con.conname, cl.relname as table_name, ref.relname as ref_table,
      array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k)::text[] as cols,
      array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k)::text[] as ref_cols
    from pg_constraint con
    join pg_class cl on cl.oid = con.conrelid
    join pg_class ref on ref.oid = con.confrelid
    join pg_namespace n on n.oid = cl.relnamespace
    join pg_namespace rn on rn.oid = ref.relnamespace
    where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
    order by con.conname`)
).rows;

const functions = (
  await db.query(`
    select p.proname as name, pg_get_function_arguments(p.oid) as args,
           p.proretset as returns_set, format_type(p.prorettype, null) as return_type,
           p.proargnames::text[] as arg_names, p.proargmodes::text[] as arg_modes,
           array(select format_type(t, null) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) t)::text[] as arg_types
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind = 'f'
      and format_type(p.prorettype, null) <> 'trigger'
      and p.proname in ('check_invitation','member_issue_invitation','member_respond_to_option','member_cancel_request','current_app_role','is_staff','is_admin','has_active_membership')
    order by p.proname`)
).rows;

function tsType(dataType, udt) {
  if (dataType === "USER-DEFINED" && enumNames.has(udt))
    return `Database["public"]["Enums"]["${udt}"]`;
  if (dataType === "ARRAY") return `${tsType(udt.replace(/^_/, ""), udt.replace(/^_/, ""))}[]`;
  switch (udt) {
    case "int2":
    case "int4":
    case "int8":
    case "float4":
    case "float8":
    case "numeric":
    case "smallint":
    case "integer":
    case "bigint":
      return "number";
    case "bool":
    case "boolean":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    default:
      return "string";
  }
}

function pgTypeToTs(t) {
  const base = t.replace(/^public\./, "");
  if (enumNames.has(base)) return `Database["public"]["Enums"]["${base}"]`;
  if (["integer", "bigint", "smallint", "numeric"].includes(base)) return "number";
  if (base === "boolean") return "boolean";
  if (base === "void") return "undefined";
  if (base === "jsonb" || base === "json") return "Json";
  return "string";
}

const byTable = new Map();
for (const col of columns) {
  if (!byTable.has(col.table_name)) byTable.set(col.table_name, []);
  byTable.get(col.table_name).push(col);
}

let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations. Do not edit.
// Regenerate with: npm run db:types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: { PostgrestVersion: "12" };
  public: {
    Tables: {
`;

for (const [table, cols] of byTable) {
  const row = cols
    .map(
      (c) =>
        `          ${c.column_name}: ${tsType(c.data_type, c.udt_name)}${c.nullable ? " | null" : ""};`,
    )
    .join("\n");
  const insert = cols
    .map((c) => {
      const optional = c.nullable || c.has_default || c.is_identity;
      return `          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.data_type, c.udt_name)}${c.nullable ? " | null" : ""};`;
    })
    .join("\n");
  const update = cols
    .map(
      (c) =>
        `          ${c.column_name}?: ${tsType(c.data_type, c.udt_name)}${c.nullable ? " | null" : ""};`,
    )
    .join("\n");
  const rels = fks
    .filter((f) => f.table_name === table)
    .map(
      (f) => `          {
            foreignKeyName: "${f.conname}";
            columns: [${f.cols.map((c) => `"${c}"`).join(", ")}];
            isOneToOne: false;
            referencedRelation: "${f.ref_table}";
            referencedColumns: [${f.ref_cols.map((c) => `"${c}"`).join(", ")}];
          },`,
    )
    .join("\n");
  out += `      ${table}: {
        Row: {
${row}
        };
        Insert: {
${insert}
        };
        Update: {
${update}
        };
        Relationships: [
${rels}
        ];
      };
`;
}

out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
for (const fn of functions) {
  const names = fn.arg_names ?? [];
  const modes = fn.arg_modes ?? [];
  const types = fn.arg_types ?? [];
  const inArgs = [];
  const outCols = [];
  names.forEach((n, i) => {
    const mode = modes[i] ?? "i";
    if (mode === "i" || mode === "b")
      inArgs.push(
        `${n}${/default/i.test(fn.args.split(",")[i] ?? "") ? "?" : ""}: ${pgTypeToTs(types[i])}`,
      );
    if (mode === "o" || mode === "t" || mode === "b") outCols.push(`${n}: ${pgTypeToTs(types[i])}`);
  });
  const returns =
    fn.returns_set && outCols.length ? `{ ${outCols.join("; ")} }[]` : pgTypeToTs(fn.return_type);
  out += `      ${fn.name}: { Args: ${inArgs.length ? `{ ${inArgs.join("; ")} }` : "Record<PropertyKey, never>"}; Returns: ${returns} };\n`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.values.map((v) => `"${v}"`).join(" | ")};`).join("\n")}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

const target = path.join(root, "src/lib/supabase/database.types.ts");
writeFileSync(target, out);
await db.end();
console.log(`✓ wrote ${path.relative(root, target)}`);
